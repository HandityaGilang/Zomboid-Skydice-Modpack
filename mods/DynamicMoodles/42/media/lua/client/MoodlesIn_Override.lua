--[[ NEW ICON TEXTURE DISPLAY CODE AND DEFAULT TO DYNAMIC MOODLES ]]--
local originalGetIconTexturePath = ISMoodlesInLua.getIconTexturePath

function ISMoodlesInLua:getIconTexturePath(moodleTranslationName)
    if self.currentMoodleIconSet == nil
    or self.currentMoodleIconSet == "Default"
    or self.currentMoodleIconSet == "Dynamic Moodles" then
        local player = self.useCharacter or getSpecificPlayer(self.playerNum) or getPlayer()

        if player and player:getMoodles() then
            local moodles = player:getMoodles()
            local values = Registries.MOODLE_TYPE:values()

            for i = 0, values:size() - 1 do
                local moodleType = values:get(i)

                if moodleType:getTranslationName() == moodleTranslationName then
                    local level = moodles:getMoodleLevel(moodleType)
                    local iconSet = self.MoodleIconMap_Custom[moodleTranslationName]

                    if level and level > 0 and iconSet and iconSet[level] then
                        return iconSet[level]
                    end

                    break
                end
            end
        end
    end

    return originalGetIconTexturePath(self, moodleTranslationName)
end

--[[ DEFAULT TO DYNAMIC MOODLES BORDERS ]]--
local originalGetBorderTexturePath = ISMoodlesInLua.getBorderTexturePath

function ISMoodlesInLua:getBorderTexturePath(goodBadNeutralId, moodleLevel)
    if self.currentMoodleBorderSet == nil
    or self.currentMoodleBorderSet == "Default"
    or self.currentMoodleBorderSet == "Dynamic Moodles Borders" then
        local borderType = goodBadNeutralId == 1 and "Good"
            or goodBadNeutralId == 2 and "Bad"
            or "Neutral"

        return string.format(
            "media/ui/MIL/DynamicMoodlesBorders/%s_%d.png",
            borderType,
            moodleLevel
        )
    end

    return originalGetBorderTexturePath(self, goodBadNeutralId, moodleLevel)
end

