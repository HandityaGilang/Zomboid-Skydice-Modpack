function VMZ_renameZoneForVanilla(ZoneX, ZoneY, NewName)
	local vz = getVehicleZoneAt(ZoneX, ZoneY, 0)
	if vz ~= nil then
		if VMZ_isModdedCell(math.floor(vz:getX()/300), math.floor(vz:getY()/300)) then return end
		vz:setName(NewName)
		vz:setOriginalName(NewName)
	end
end

function VMZ_renameZone(ZoneX, ZoneY, NewName)
	local vz = getVehicleZoneAt(ZoneX, ZoneY, 0)
	if vz ~= nil then
		vz:setName(NewName)
		vz:setOriginalName(NewName)
	end
end

